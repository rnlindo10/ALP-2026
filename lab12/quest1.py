# função print() recebe argumentos e os imprime na tela
# Exemplo:
print("Olá, mundo!")

# função type() recebe um objeto como argumento e retorna qual é o seu tipo (int, str, float, etc).
# Exemplo:
tipo = type(10.5)

# função len() recebe uma sequência (como uma string ou lista) e retorna o número de itens/caracteres.
# Exemplo:
tamanho = len("Python")